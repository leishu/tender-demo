-- =====================================================================
-- 一次性升级脚本：t_tender_task 记录本次任务使用的 Agent 会话 ID
--
-- 背景：
--   会话 ID 现在只由服务端签发。客户端要续写，必须拿到「上一次用的是哪个会话」，
--   而目录生成/调整、章节撰写这三个接口只返回业务结果，没有任务对象可挂字段。
--   把会话 ID 落在任务行上，响应时再回给客户端（X-Session-Id 响应头），
--   幂等命中时还能返回「原任务的那个会话」，而不是又发一个新的。
--
-- 说明：
--   - 列可为 NULL：改造前创建的历史任务没有记录会话，无法回填，也不影响历史数据读取。
--     服务端在命中这类老任务时会补发一个新 ID 并回写本列，保证响应里给出的 ID 可查。
--   - 不需要索引：目前没有按会话反查任务的场景。
--
-- 仅对已经按旧版 DDL 建过库的环境执行；全新环境直接执行
-- src/main/db/tender_task.sql 即可，不需要本脚本。
--
-- 执行：mysql -u root -p tender_demo < src/main/db/upgrade/2026-11-13-add-task-session-id.sql
-- =====================================================================

ALTER TABLE `t_tender_task`
    ADD COLUMN `session_id` VARCHAR(191) NULL
        COMMENT '本次任务使用的 Agent 会话ID（服务端签发）；客户端续写时原样回传'
        AFTER `idempotency_key`;
